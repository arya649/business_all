#!/usr/bin/env node
// Turns config/feature-registry.json into the SQL migration that loads the feature catalogue.
// Run after editing the registry:  node scripts/gen-feature-catalog.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const registry = JSON.parse(readFileSync(join(root, "config/feature-registry.json"), "utf8"));
const out = join(root, "supabase/migrations/20261030000006_feature_catalog.sql");

const ACRONYMS = { gst: "GST", tds: "TDS", tcs: "TCS", rmc: "RMC", dpr: "DPR", boq: "BOQ", ra: "RA", po: "PO", grn: "GRN",
  rfq: "RFQ", dsr: "DSR", atg: "ATG", gps: "GPS", rfid: "RFID", anpr: "ANPR", pf: "PF", esi: "ESI", pt: "PT", lwf: "LWF",
  ai: "AI", ocr: "OCR", hr: "HR", crm: "CRM", jmf: "JMF", upi: "UPI", pos: "POS", emd: "EMD", bg: "BG", gstr1: "GSTR-1",
  gstr2b: "GSTR-2B", gstr3b: "GSTR-3B", m3: "m³" };
const label = (k) => k.split("_").map((w, i) => ACRONYMS[w] ?? (i === 0 ? w[0].toUpperCase() + w.slice(1) : w)).join(" ");
const q = (s) => (s === null ? "null" : `'${String(s).replaceAll("'", "''")}'`);

const rows = [];
let sort = 0;
function walk(node, parent) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$") || key === "config") continue;
    const full = parent ? `${parent}.${key}` : key;
    const cfg = child.config ? JSON.stringify(child.config) : "{}";
    rows.push(`(${q(full)}, ${q(parent)}, ${q(label(key))}, ${q(cfg)}::jsonb, ${sort++})`);
    walk(child, full);
  }
}
walk(registry, null);

writeFileSync(out, `-- GENERATED by scripts/gen-feature-catalog.mjs from config/feature-registry.json. Do not edit by hand.
-- Parents are listed before children, so a single insert satisfies the parent foreign key.

insert into public.feature (key, parent_key, label, default_config, sort) values
${rows.join(",\n")}
on conflict (key) do update set
  parent_key = excluded.parent_key,
  label = excluded.label,
  default_config = excluded.default_config,
  sort = excluded.sort;
`);
console.log(`wrote ${rows.length} features to ${out}`);
